import { z } from 'zod'
import type { ProjectConfig } from './types'

export const projectConfigSchema = z
  .object({
    schemaVersion: z.literal(1),
    name: z.string().min(1).max(80).optional(),
    packages: z
      .record(
        z.string().regex(/^[a-z0-9][a-z0-9-]*$/).max(80),
        z.string().min(1).max(120)
      )
      .refine((value) => Object.keys(value).length > 0, 'Select at least one package.')
  })
  .strict()

export type ParsedProjectConfig = z.infer<typeof projectConfigSchema>

export function parseProjectConfig(
  input: unknown
): { ok: true; value: ProjectConfig } | { ok: false; issues: string[] } {
  const parsed = projectConfigSchema.safeParse(input)
  if (!parsed.success) {
    return {
      ok: false,
      issues: parsed.error.issues.map((issue) => `${issue.path.join('.') || '(root)'}: ${issue.message}`)
    }
  }
  return { ok: true, value: parsed.data as ProjectConfig }
}

export interface ProjectActivationEntry {
  packageId: string
  name: string
  version: string
  installDir: string
  environment: { kind: 'path' | 'variable'; name: string; value: string }[]
}

function quote(value: string): string {
  return `'${value.replace(/'/g, "''")}'`
}

/**
 * Builds a self-contained PowerShell activation script. It only changes the
 * current shell process; it never edits user or system environment variables.
 */
export function buildActivationScript(entries: ProjectActivationEntry[], projectName: string): string {
  const pathEntries: string[] = []
  const variables: { name: string; value: string }[] = []
  const labels: string[] = []

  for (const entry of entries) {
    labels.push(`${entry.name} ${entry.version}`)
    for (const spec of entry.environment) {
      if (spec.kind === 'path') {
        if (!pathEntries.includes(spec.value)) pathEntries.push(spec.value)
      } else if (!variables.some((variable) => variable.name.toLowerCase() === spec.name.toLowerCase())) {
        variables.push({ name: spec.name, value: spec.value })
      }
    }
    if (!entry.environment.some((spec) => spec.kind === 'path') && entry.installDir) {
      if (!pathEntries.includes(entry.installDir)) pathEntries.push(entry.installDir)
    }
  }

  const lines: string[] = []
  lines.push('# Generated by DevForge. Dot-source this file from PowerShell:')
  lines.push('#   . .\\.devforge\\activate.ps1')
  lines.push(`# Project: ${projectName.replace(/[\r\n]/g, ' ')}`)
  lines.push('$ErrorActionPreference = "Stop"')
  lines.push('if (-not $env:DEVFORGE_ORIGINAL_PATH) { $env:DEVFORGE_ORIGINAL_PATH = $env:PATH }')
  lines.push('')
  if (pathEntries.length > 0) {
    lines.push('$devforgePaths = @(')
    for (const entry of pathEntries) lines.push(`  ${quote(entry)}`)
    lines.push(')')
    lines.push('foreach ($devforgeDir in $devforgePaths) {')
    lines.push('  if ($devforgeDir -and (Test-Path -LiteralPath $devforgeDir)) {')
    lines.push('    $env:PATH = "$devforgeDir;$env:PATH"')
    lines.push('  } else {')
    lines.push('    Write-Warning "DevForge project path is missing: $devforgeDir"')
    lines.push('  }')
    lines.push('}')
    lines.push('')
  }
  for (const variable of variables) {
    lines.push(`$env:${variable.name} = ${quote(variable.value)}`)
  }
  if (variables.length > 0) lines.push('')
  lines.push(`Write-Host "DevForge project environment active: ${labels.join(', ').replace(/"/g, '`"')}" -ForegroundColor Green`)
  lines.push('Write-Host "Run . .\\.devforge\\deactivate.ps1 to restore this shell." -ForegroundColor DarkGray')
  lines.push('')
  return lines.join('\r\n')
}

export function buildDeactivationScript(): string {
  return [
    '# Generated by DevForge. Restores the PATH captured by activate.ps1.',
    'if ($env:DEVFORGE_ORIGINAL_PATH) {',
    '  $env:PATH = $env:DEVFORGE_ORIGINAL_PATH',
    '  Remove-Item Env:DEVFORGE_ORIGINAL_PATH -ErrorAction SilentlyContinue',
    '  Write-Host "DevForge project environment deactivated." -ForegroundColor Yellow',
    '} else {',
    '  Write-Host "No DevForge project environment is active in this shell." -ForegroundColor DarkGray',
    '}',
    ''
  ].join('\r\n')
}
